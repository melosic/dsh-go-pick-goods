export function apply(ctx) {
  ctx.inject(['dshGo'], (ctx) => {
    const handlers = {
      brief: () => ({ insert: BRIEF_HEAD }),
      vet: () => ({ insert: CHECK_HEAD }),
      'open-book': () => ({ open: 'panel:book' }),
      'open-std': () => ({ open: 'panel:std' }),
      ...Object.fromEntries(Object.entries(BY_CATEGORY).map(([k, v]) => [`cat:${k}`, () => ({ insert: v })])),
      ...Object.fromEntries(Object.entries(SCRIPTS).map(([k, v]) => [`say:${k}`, () => ({ insert: v })])),
      ...Object.fromEntries(Object.entries(PLATFORM).map(([k, p]) => [`plat:${k}`, () => ({ insert: p.text + '\n\n我要买的是：', toast: '已切到' + p.name })])),
    }
    ctx.dshGo.panel('book', { view: () => book(), actions: handlers })
    ctx.dshGo.panel('entry', { view: () => entry(), actions: handlers })
    ctx.dshGo.panel('std', {
      view: () => std(),
      actions: { ...handlers, 'copy-warn': () => ({ copy: WARN_LINES, toast: '警戒线已复制' }) },
    })
  })
}
